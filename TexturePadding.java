import javax.imageio.ImageIO;
import java.awt.image.BufferedImage;
import java.util.List;
import java.io.File;
import java.nio.file.Files;
import java.nio.file.Path;

BufferedImage img;
StringBuilder hppOut = new StringBuilder();
StringBuilder out = new StringBuilder();

final boolean PADDING = true;
final boolean TEXTURES_IN_FLASH = false;

void main(String[] args) throws Throwable {
    hppOut.append("// Generated by TexturePadding.java\n");
    hppOut.append("\n");
    hppOut.append("#pragma once\n");
    hppOut.append("\n");
    hppOut.append("#include <cstdint>");
    hppOut.append("\n");
    hppOut.append("const int TEXTURE_STRIDE_BITS = " + (PADDING ? 5 : 4) + ";\n");
    hppOut.append("const int TEXTURE_STRIDE = 1 << TEXTURE_STRIDE_BITS;\n");
    hppOut.append("const int TEXTURE_SIZE_BITS = " + 4 + ";\n");
    hppOut.append("const int TEXTURE_SIZE = 1 << TEXTURE_SIZE_BITS;\n");
    hppOut.append("\n");

    out.append("// Generated by TexturePadding.java\n");
    out.append("\n");
    out.append("#include \"textures.hpp\"\n");
    out.append("\n");

    processFile("dirt.png", "DIRT_TEXTURE");
    processFile("grass_side.png", "GRASS_SIDE_TEXTURE");
    processFile("grass_top.png", "GRASS_TOP_TEXTURE");

    Files.writeString(Path.of("textures.cpp"), out.toString());
    Files.writeString(Path.of("textures.hpp"), hppOut.toString());
}

void processFile(String filename, String variableName) throws Throwable {
    out.append("\n");

    img = ImageIO.read(new File(filename));
    if (img.getWidth() != 16 || img.getHeight() != 16)
        throw new RuntimeException("wrong image size");

    hppOut.append("extern const uint16_t* " + variableName + ";\n");

    if (TEXTURES_IN_FLASH)
        out.append("const ");
    if (PADDING) {
        out.append("uint16_t "+variableName+"_PADDED[] = {\n");
        for (int row = 0; row < 18; row++) {
            out.append("\t");
            for (int col = 0; col < 18; col++) {
                int srcRow = Math.max(0, Math.min(15, row - 1));
                int srcCol = Math.max(0, Math.min(15, col - 1));
                RGB color = at(srcCol, srcRow);
                out.append(String.format("0x%04x, ", color.toRGB565()));
            }
            for (int col = 18; col < 32; col++) {
                out.append("0, ");
            }
            out.append("\n");
        }
        out.append("};\n");
        out.append("const uint16_t* "+variableName+" = &" + 
            variableName + "_PADDED[32 + 1];\n");
    } else {
        // azért kell külön változóba rakni, mert különben reklemál cpmféoctomg declaration miatt
        out.append("uint16_t "+variableName+"_DATA[] = {\n");
        for (int row = 0; row < 16; row++) {
            out.append("\t");
            for (int col = 0; col < 16; col++) {
                RGB color = at(col, row);
                out.append(String.format("0x%04x, ", color.toRGB565()));
            }
            out.append("\n");
        }
        out.append("};\n");
        out.append("const uint16_t* "+variableName+" = &" + 
            variableName + "_DATA;\n");
    }
}

record RGB(int r, int g, int b) {
    
    int toRGB565() {
        return r >>> 3 << 11 | g >>> 2 << 5 | b >>> 3;
    }
}

RGB at(int x, int y) {
    int rgba = img.getRGB(x, y);
    int r = rgba >>> 16 & 0xFF;
    int g = rgba >>> 8 & 0xFF;
    int b = rgba & 0xFF;
    return new RGB(r, g, b);
}
