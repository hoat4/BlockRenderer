import javax.imageio.ImageIO;
import java.awt.image.BufferedImage;
import java.util.List;
import java.io.File;
import java.nio.file.Files;
import java.nio.file.Path;

BufferedImage img;
StringBuilder hppOut = new StringBuilder();
StringBuilder out = new StringBuilder();

final boolean PADDING = true;
final boolean TEXTURES_IN_FLASH = false;
final int TEXTURE_SIZE = 16;
int scale;

void main(String[] args) throws Throwable {
    hppOut.append("// Generated by TexturePadding.java\n");
    hppOut.append("\n");
    hppOut.append("#pragma once\n");
    hppOut.append("\n");
    hppOut.append("#include <cstdint>");
    hppOut.append("\n");
    hppOut.append("const int TEXTURE_STRIDE_BITS = " + (PADDING ? 5 : 4) + ";\n");
    hppOut.append("const int TEXTURE_STRIDE = 1 << TEXTURE_STRIDE_BITS;\n");
    hppOut.append("const int TEXTURE_SIZE_BITS = " + 4 + ";\n");
    hppOut.append("const int TEXTURE_SIZE = 1 << TEXTURE_SIZE_BITS;\n");
    hppOut.append("\n");

    out.append("// Generated by TexturePadding.java\n");
    out.append("\n");
    out.append("#include \"textures.hpp\"\n");
    out.append("\n");

    processFile("dirt.png", "DIRT_TEXTURE", 1);
    processFile("grass_side.png", "GRASS_SIDE_TEXTURE", 1);
    processFile("grass_top.png", "GRASS_TOP_TEXTURE", 1);
    processFile("planks_oak.png", "OAK_PLANKS_TEXTURE", 1);
    processFile("log_oak_top.png", "OAK_LOG_TOP_TEXTURE", 1);
    processFile("log_oak.png", "OAK_LOG_SIDE_TEXTURE", 1);
    processFile("oak_leaves_opaque.png", "OAK_LEAVES_TEXTURE", 1);
    
    processFile("water_flow.png", "WATER_FLOW_TEXTURES", 32);

    Files.writeString(Path.of("textures.cpp"), out.toString());
    Files.writeString(Path.of("textures.hpp"), hppOut.toString());
}

void processFile(String filename, String variableName, int n) throws Throwable {
    out.append("\n");

    img = ImageIO.read(new File("textures/" + filename));
    if (img.getWidth() % TEXTURE_SIZE != 0 || img.getHeight() < img.getWidth() * n || img.getHeight() % img.getWidth() != 0)
        throw new RuntimeException("wrong image size");
    scale = img.getWidth() / TEXTURE_SIZE;
    String[] refs = new String[n];

    for (int i = 0; i < n; i++) {
        String frameNumberSuffix = n != 1 ? "_" + i : "";
        refs[i] = generateTextureFrame(variableName + frameNumberSuffix, i);
    }

    if (n != 1) {
        hppOut.append("extern const uint16_t* " + variableName + "[" + n + "];\n");
        hppOut.append("const uint16_t " + variableName + "_COUNT = " + n + ";\n");
        out.append("const uint16_t* " + variableName + "[" + n + "] = {\n");
        for (int i = 0; i < n; i++) {
            out.append("    ").append(refs[i]).append(i == n - 1 ? "\n" : ",\n");
        }
        out.append("};");
    } else {
        hppOut.append("extern const uint16_t* " + variableName + ";\n");
        out.append("const uint16_t* "+variableName+" = " + refs[0] + ";");
    }
}

/**
 * @return referecing code snippet
 */
String generateTextureFrame(String variableName, int i) {
    if (TEXTURES_IN_FLASH)
        out.append("const ");
    if (PADDING) {
        out.append("uint16_t " + variableName + "_PADDED[] = {\n");
        for (int row = 0; row < TEXTURE_SIZE + 2; row++) {
            out.append("\t");
            for (int col = 0; col < TEXTURE_SIZE + 2; col++) {
                int srcRow = Math.max(0, Math.min(TEXTURE_SIZE - 1, row - 1));
                int srcCol = Math.max(0, Math.min(TEXTURE_SIZE - 1, col - 1));
                RGB color = at(srcCol, i * TEXTURE_SIZE + srcRow);
                out.append(String.format("0x%04x, ", color.toRGB565()));
            }
            for (int col = TEXTURE_SIZE + 2; col < TEXTURE_SIZE * 2; col++) {
                out.append("0, ");
            }
            out.append("\n");
        }
        out.append("};\n");
        return "&" + variableName + "_PADDED[2 * " + TEXTURE_SIZE + " + 1]";
    } else {
        // azért kell külön változóba rakni, mert különben reklemál conflicting declaration miatt
        out.append("uint16_t " + variableName + "_DATA[] = {\n");
        for (int row = 0; row < TEXTURE_SIZE; row++) {
            out.append("\t");
            for (int col = 0; col < TEXTURE_SIZE; col++) {
                RGB color = at(col, i * TEXTURE_SIZE + row);
                out.append(String.format("0x%04x, ", color.toRGB565()));
            }
            out.append("\n");
        }
        out.append("};\n");    
        return "&" + variableName + "_DATA";
    }
}

record RGB(int r, int g, int b) {
    
    int toRGB565() {
        return r >>> 3 << 11 | g >>> 2 << 5 | b >>> 3;
    }
}

RGB at(int x, int y) {
    int rSum = 0, gSum = 0, bSum = 0;
    for (int x2 = 0; x2 < scale; x2++) {
        for (int y2 = 0; y2 < scale; y2++) {
            int rgba = img.getRGB(x * scale + x2, y * scale + y2);
            rSum += rgba >>> 16 & 0xFF;
            gSum += rgba >>> 8 & 0xFF;
            bSum += rgba & 0xFF;
        }
    }
    int n = scale * scale;
    return new RGB(rSum / n, gSum / n, bSum / n);
}
