import javax.imageio.ImageIO;
import java.awt.image.BufferedImage;
import java.util.List;
import java.io.File;
import java.nio.file.Files;
import java.nio.file.Path;

BufferedImage img;
StringBuilder out = new StringBuilder();

void main(String[] args) throws Throwable {
    out.append("// Generated by TexturePadding.java\n");

    processFile("dirt.png", "DIRT_TEXTURE");
    processFile("grass_side.png", "GRASS_SIDE_TEXTURE");
    processFile("grass_top.png", "GRASS_TOP_TEXTURE");

    Files.writeString(Path.of("textures.hpp"), out.toString());
}

void processFile(String filename, String variableName) throws Throwable {
    out.append("\n");

    img = ImageIO.read(new File(filename));
    if (img.getWidth() != 16 || img.getHeight() != 16)
        throw new RuntimeException("wrong image size");

    out.append("const uint16_t "+variableName+"[] = {\n");
    for (int row = 0; row < 16; row++) {
        out.append("\t");
        for (int col = 0; col < 16; col++) {
            RGB color = at(col, row);
            out.append(String.format("0x%04x, ", color.toRGB565()));
        }
        out.append("\n");
    }
    out.append("};\n");
}

record RGB(int r, int g, int b) {
    
    int toRGB565() {
        return r >>> 3 << 11 | g >>> 2 << 5 | b >>> 3;
    }
}

RGB at(int x, int y) {
    int rgba = img.getRGB(x, y);
    int r = rgba >>> 16 & 0xFF;
    int g = rgba >>> 8 & 0xFF;
    int b = rgba & 0xFF;
    return new RGB(r, g, b);
}
